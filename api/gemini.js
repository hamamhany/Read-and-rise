// ينظّف سجل المحادثة بحيث يصير بالشكل اللي يقبله Gemini:
// أدوار متبادلة، وأول رسالة من المستخدم.
const buildContents = (history, message) => {
  const raw = [
    ...(Array.isArray(history) ? history.slice(-12) : []),
    { role: 'user', text: message },
  ];
 
  const out = [];
  for (const item of raw) {
    const text = typeof item?.text === 'string' ? item.text.trim().slice(0, 2000) : '';
    if (!text) continue;
    const role = item?.role === 'model' ? 'model' : 'user';
    const last = out[out.length - 1];
    if (last && last.role === role) {
      last.parts[0].text += '\n' + text;
    } else {
      out.push({ role, parts: [{ text }] });
    }
  }
 
  while (out.length && out[0].role !== 'user') out.shift();
  return out;
};
 
export default async function handler(req, res) {
  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method not allowed' });
  }
 
  try {
    const body = typeof req.body === 'string' ? JSON.parse(req.body) : req.body;
    const message = typeof body?.message === 'string' ? body.message.trim() : '';
    const history = body?.history;
 
    if (!message) {
      return res.status(400).json({ error: 'Message is required' });
    }
 
    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey) {
      return res.status(500).json({ error: 'GEMINI_API_KEY is not configured' });
    }
 
    const hasGreeted =
      Array.isArray(history) && history.some((h) => h?.role === 'model');
 
    const ai = new GoogleGenAI({
      apiKey,
      httpOptions: { timeout: 55000 },
    });
 
    const response = await ai.models.generateContent({
      model: MODEL,
      contents: buildContents(history, message),
      config: {
        systemInstruction: buildSystemInstruction(hasGreeted),
        temperature: 0.3,
      },
    });
 
    return res.status(200).json({ text: response.text });
  } catch (error) {
    console.error('Gemini API Error:', error);
    return res.status(500).json({ error: 'Failed to generate content from Gemini' });
  }
}
 